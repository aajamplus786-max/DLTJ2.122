import {
  Router,
} from "express";

import {
  register,
  login,
  verifyOTP,
  resend,
  status,
  logout,
} from "../controllers/authController";

const router =
  Router();

// =====================================================
// REGISTER
// =====================================================

router.post(
  "/register",
  register,
);

// =====================================================
// LOGIN
// =====================================================

router.post(
  "/login",
  login,
);

// =====================================================
// VERIFY OTP
// =====================================================

router.post(
  "/verify-otp",
  verifyOTP,
);

// =====================================================
// RESEND OTP
// =====================================================

router.post(
  "/resend-otp",
  resend,
);

// =====================================================
// STATUS
// =====================================================

router.get(
  "/status",
  status,
);

// =====================================================
// LOGOUT
// =====================================================

router.post(
  "/logout",
  logout,
);

export default router;